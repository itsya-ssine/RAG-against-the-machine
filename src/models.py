"""Pydantic data models exchanged between the stages of the RAG pipeline."""

import uuid
from typing import List

from pydantic import BaseModel, Field


class MinimalSource(BaseModel):
    """A source location inside the indexed corpus.

    Attributes:
        file_path: Path of the file, written exactly as in the corpus
            (e.g. ``data/raw/vllm-0.10.1/docs/features/lora.md``).
        first_character_index: Index of the first character of the span.
        last_character_index: Index of the last character of the span.
    """

    file_path: str
    first_character_index: int
    last_character_index: int


class UnansweredQuestion(BaseModel):
    """A question for which no answer is known yet.

    Attributes:
        question_id: Unique identifier (a UUID4 is generated by default).
        question: The question text.
    """

    question_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    question: str


class AnsweredQuestion(UnansweredQuestion):
    """A question together with its ground-truth sources and answer.

    Attributes:
        sources: Source locations that contain the answer.
        answer: The reference answer.
    """

    sources: List[MinimalSource]
    answer: str


class RagDataset(BaseModel):
    """A dataset of RAG questions, answered or not.

    Attributes:
        rag_questions: The questions of the dataset.
    """

    rag_questions: List[AnsweredQuestion | UnansweredQuestion]


class MinimalSearchResults(BaseModel):
    """Search results for a single question.

    Attributes:
        question_id: Identifier of the question.
        question: The question text.
        retrieved_sources: Ranked sources returned by the retriever.
    """

    question_id: str
    question: str
    retrieved_sources: List[MinimalSource]


class MinimalAnswer(MinimalSearchResults):
    """Search results for a question plus the generated answer.

    Attributes:
        answer: The answer generated from the retrieved sources.
    """

    answer: str


class StudentSearchResults(BaseModel):
    """Output of the search commands.

    Attributes:
        search_results: One entry per question.
        k: Number of results requested per question.
    """

    search_results: List[MinimalSearchResults]
    k: int


class StudentSearchResultsAndAnswer(BaseModel):
    """Output of the answer commands.

    Attributes:
        search_results: One answered entry per question.
        k: Number of results requested per question.
    """

    search_results: List[MinimalAnswer]
    k: int
